#!/usr/bin/env python3
"""Regenerate the bundled dictionary (Python standard library only).

Run `python3 scripts/generate_pinyin.py` to fetch the pinned source, or pass
`--source /path/to/pinyin.txt` to regenerate offline from an existing download.
The source hash is checked in either case. Users of Flash do not need Python.
"""

import argparse
import hashlib
from pathlib import Path
import re
import unicodedata
import urllib.request


REVISION = "9d05c9e29cb6a7e5c79f2f5279f5c1014246a19a"
SOURCE_URL = f"https://raw.githubusercontent.com/mozillazg/pinyin-data/{REVISION}/pinyin.txt"
SOURCE_SHA256 = "90c11bd680ccfe7f2617a6e25abdb1fb87b5540df3e6f011ca50aaf3c7263a89"
ROOT = Path(__file__).resolve().parents[1]


def normalize(reading):
    # Preserve the u/ü distinction before removing tone and other diacritics.
    decomposed = unicodedata.normalize("NFD", reading).replace("u\u0308", "v")
    syllable = "".join(char for char in decomposed if not unicodedata.combining(char))
    if not re.fullmatch("[a-z]+", syllable):
        raise ValueError(f"Unsupported reading: {reading!r}")
    return syllable


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="use a local copy of the pinned pinyin.txt")
    parser.add_argument("--output", type=Path, default=ROOT / "lua/flash/pinyin/data.lua")
    args = parser.parse_args()
    if args.source:
        source = args.source.read_bytes()
    else:
        with urllib.request.urlopen(SOURCE_URL, timeout=60) as response:
            source = response.read()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("Source SHA-256 mismatch; refusing to generate from unexpected data")

    syllables = {}
    characters = set()
    for line in source.decode("utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        codepoint, readings = line.split(":", 1)
        char = chr(int(codepoint.removeprefix("U+"), 16))
        characters.add(char)
        for reading in readings.strip().split(","):
            syllables.setdefault(normalize(reading), set()).add(char)

    lines = [
        "-- Generated by scripts/generate_pinyin.py; do not edit.",
        f"-- Source: mozillazg/pinyin-data (MIT), revision {REVISION}",
        "-- License: third-party/pinyin-data-LICENSE",
        f"-- {len(characters)} characters; {len(syllables)} untoned syllables; no excluded readings.",
        "-- stylua: ignore",
        "return {",
    ]
    for syllable, chars in sorted(syllables.items()):
        lines.append(f'  ["{syllable}"] = "{"".join(sorted(chars))}",')
    lines.extend(["}", ""])
    output = "\n".join(lines)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8")
    print(f"Wrote {args.output}: {len(characters)} characters, {len(syllables)} syllables, "
          f"{len(output.encode('utf-8'))} bytes, no excluded readings")


if __name__ == "__main__":
    main()
